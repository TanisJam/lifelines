/**
 * RI1d (specs S2, S8): the existing read routes dispatch on persistence. A life with a
 * `lifecycle_lives` row is served from a FULL replay of its capsule; every other life keeps the
 * legacy store and the legacy builder, with today's exact ordering and error texts.
 *
 * The lifecycle lives here are published directly through `LifecycleRepository` with a small
 * (4-founder) world so the file stays cheap: what this file proves is the ROUTE behavior — which
 * engine served a response, the list order, and the error envelopes — while
 * `lifecycle-read.test.ts` proves the full create path (`lifecycle-life.ts`, default world).
 */
const initialization = (seed: string, name: string) => ({
  seed, startYear: 1327, endYear: 1327, founderCount: 4, protagonist: { name, sex: "f" as const },
});

/** One complete lifecycle life, regenerated by the runtime itself (2048-step safety bound). */
async function completedSource(seed: string, name: string): Promise<LifecycleProjectionSource> {
  const { world } = initializeWorld(initialization(seed, name));
  const genesis = createLifecycleGenesis({
    initialization: initialization(seed, name),
    protagonistId: "protagonist",
    resources: Object.fromEntries(Object.keys(world.people).map((id) => [id, { grain: 2, effort: 3, need: 1 }])),
  });
  const runtime = createLifecycleRuntime(genesis);
  let output = runtime.snapshot();
  for (let steps = 0; output.status !== "complete" && steps < 128; steps++) output = await runtime.advance(output.frontier + 1);
  if (output.status !== "complete") throw new Error(`fixture life did not end: ${output.status}`);
  return { genesis, output };
}

interface Fixture {
  readonly lifeId: string;
  readonly branchId: string;
  /** An INDEPENDENT regeneration of the same inputs, never the bytes that were published. */
  readonly source: LifecycleProjectionSource;
  readonly chronicle: Chronicle;
}

async function publishLifecycleLife(lifeId: string, branchId: string, seed: string, name: string): Promise<Fixture> {
  const { world } = initializeWorld(initialization(seed, name));
  const published = await completedSource(seed, name);
  const source = await completedSource(seed, name);
  await new LifecycleRepository(getDb()).publish({
    lifeId,
    branchId,
    config: world.config,
    protagonistName: world.people.protagonist!.name,
    protagonistSex: world.people.protagonist!.sex as LifeSex,
    capsule: await createLifecycleCompactCapsule(published),
  });
  const chronicle = (await projectLifecycleChronicle({
    source, identity: { lifeId, branchId }, locale: "en",
  })).view;
  return { lifeId, branchId, source, chronicle };
}

/** One lifecycle life still alive at its horizon: a one-year advance, the state specs S1/S5 display. */
async function aliveSource(seed: string, name: string): Promise<LifecycleProjectionSource> {
  const { world } = initializeWorld(initialization(seed, name));
  const genesis = createLifecycleGenesis({
    initialization: initialization(seed, name),
    protagonistId: "protagonist",
    resources: Object.fromEntries(Object.keys(world.people).map((id) => [id, { grain: 2, effort: 3, need: 1 }])),
  });
  const output = await createLifecycleRuntime(genesis).advance(1327);
  if (output.status !== "incomplete") throw new Error(`fixture life did not stay alive: ${output.status}`);
  return { genesis, output };
}

async function publishAliveLifecycleLife(lifeId: string, branchId: string, seed: string, name: string): Promise<void> {
  const { world } = initializeWorld(initialization(seed, name));
  await new LifecycleRepository(getDb()).publish({
    lifeId,
    branchId,
    config: world.config,
    protagonistName: world.people.protagonist!.name,
    protagonistSex: world.people.protagonist!.sex as LifeSex,
    capsule: await createLifecycleCompactCapsule(await aliveSource(seed, name)),
  });
}

async function registerLegacyLife(): Promise<{ lifeId: string; branchId: string }> {  const { config, people, events } = generateWorld({
    seed: "ri1d-route-legacy-1", startYear: 1500, endYear: 1600, founderCount: 10,
    protagonist: { name: "Testa", sex: "random" },
  });
  const report = await simulate(config, people, events, {
    decisionMaker: new RuleDecisionMaker(), engineSource: "rules", protagonistId: "protagonist",
  });
  const protagonist = report.result.people.protagonist!;
  const life = registerLife("legacy-ri1d-route-1", "branch-legacy-ri1d-route-1", config, protagonist.name, protagonist.sex, report.result, report.snapshots);
  return { lifeId: life.id, branchId: life.originalBranchId };
}

const FIRST = { lifeId: "life-ri1d-route-1", branchId: "branch-ri1d-route-1", seed: "ri1d-route-1", name: "Alice" };
const SECOND = { lifeId: "life-ri1d-route-2", branchId: "branch-ri1d-route-2", seed: "ri1d-route-2", name: "Beatrice" };

let first: Fixture;
let second: Fixture;
let legacy: Awaited<ReturnType<typeof registerLegacyLife>>;

beforeAll(async () => {
  first = await publishLifecycleLife(FIRST.lifeId, FIRST.branchId, FIRST.seed, FIRST.name);
  second = await publishLifecycleLife(SECOND.lifeId, SECOND.branchId, SECOND.seed, SECOND.name);
  legacy = await registerLegacyLife();
}, 240_000);

afterAll(() => {
  try { getDb().close(); } catch { /* Never opened. */ }
});

function listRequest(): Request {
  return new Request("http://local/api/lives?lang=en");
}
function lifeRequest(lifeId: string, branchId?: string): Request {
  return new Request(`http://local/api/lives/${lifeId}${branchId === undefined ? "" : `?branchId=${branchId}`}`);
}
function personRequest(lifeId: string, personId: string): Request {
  return new Request(`http://local/api/lives/${lifeId}/people/${personId}`);
}

describe("GET /api/lives — list activation (RI1d)", () => {
  it("appends lifecycle lives after the untouched legacy rows, newest first", async () => {
    const response = await getLives(listRequest());
    expect(response.status).toBe(200);
    const items = (await response.json()) as LifeListItem[];

    const summaries = listLifeSummaries();
    // Legacy rows keep the order the legacy store returns them in; nothing is re-sorted, filtered
    // or renumbered by the activation.
    expect(items.slice(0, summaries.length).map((item) => item.lifeId)).toEqual(summaries.map((summary) => summary.id));
    // A legacy row still reports the legacy life's own facts, mapped exactly as before.
    const summary = summaries.find((candidate) => candidate.id === legacy.lifeId)!;
    const protagonist = summary.latestResult.people.protagonist!;
    const deathYear = protagonist.deathYear ?? summary.config.endYear;
    const legacyItem = items.find((item) => item.lifeId === legacy.lifeId)!;
    expect(legacyItem).toEqual({
      lifeId: summary.id,
      name: summary.protagonistName,
      birthYear: summary.config.startYear,
      deathYear,
      ageAtDeath: deathYear - summary.config.startYear,
      causeOfDeath: expect.any(String),
      branchCount: summary.branchCount,
    });
    if (legacyItem.causeOfDeath === null) throw new Error("A legacy list row always carries a cause.");
    expect(legacyItem.causeOfDeath.length).toBeGreaterThan(0);

    // Lifecycle rows follow, newest first by their own `created_at`, each derived from its replay.
    expect(items.slice(summaries.length)).toEqual([
      {
        lifeId: SECOND.lifeId, name: SECOND.name, birthYear: second.chronicle.protagonist.birthYear,
        deathYear: second.chronicle.protagonist.deathYear, ageAtDeath: second.chronicle.protagonist.ageAtDeath,
        causeOfDeath: second.chronicle.protagonist.causeOfDeath, branchCount: 1,
      },
      {
        lifeId: FIRST.lifeId, name: FIRST.name, birthYear: first.chronicle.protagonist.birthYear,
        deathYear: first.chronicle.protagonist.deathYear, ageAtDeath: first.chronicle.protagonist.ageAtDeath,
        causeOfDeath: first.chronicle.protagonist.causeOfDeath, branchCount: 1,
      },
    ]);
  }, 120_000);

  it("serves a life alive at its horizon as alive, in the list and in the detail", async () => {
    // Specs S1/S5: the wire carries an explicit absence for every death field, never a borrowed
    // death year, age or cause, plus the horizon the life reached alive.
    const alive = { lifeId: "life-ri1d-route-alive", branchId: "branch-ri1d-route-alive", seed: "ri1d-route-alive", name: "Clara" };
    await publishAliveLifecycleLife(alive.lifeId, alive.branchId, alive.seed, alive.name);

    const listed = (await (await getLives(listRequest())).json()) as LifeListItem[];
    expect(listed.find((item) => item.lifeId === alive.lifeId)).toEqual({
      lifeId: alive.lifeId, name: alive.name, birthYear: 1327,
      deathYear: null, ageAtDeath: null, causeOfDeath: null, horizonYear: 1327, branchCount: 1,
    });

    const response = await getLife(lifeRequest(alive.lifeId), { params: Promise.resolve({ lifeId: alive.lifeId }) });
    expect(response.status).toBe(200);
    const chronicle = (await response.json()) as Chronicle;
    expect(chronicle.protagonist).toEqual({
      name: alive.name, sex: "f", birthYear: 1327,
      deathYear: null, ageAtDeath: null, causeOfDeath: null, horizonYear: 1327,
    });
    expect(chronicle.epilogue).toEqual([]);
    expect(chronicle.entries.some((entry) => entry.kind === "death")).toBe(false);
  }, 120_000);
});

describe("GET /api/lives/:lifeId — detail activation (RI1d)", () => {
  it("serves a lifecycle life from its regenerated capsule and a legacy life from the legacy builder", async () => {
    const response = await getLife(lifeRequest(FIRST.lifeId), { params: Promise.resolve({ lifeId: FIRST.lifeId }) });
    expect(response.status).toBe(200);
    const chronicle = (await response.json()) as Chronicle;
    expect(chronicle).toEqual(first.chronicle);
    // The engine has one branch: no branch switcher is invented for a lifecycle life.
    expect(chronicle.branches).toEqual([]);

    // The legacy life still gets its real legacy chronicle, including its branch metadata — the
    // observable proof that the legacy builder (not the lifecycle one) served it.
    const legacyResponse = await getLife(lifeRequest(legacy.lifeId), { params: Promise.resolve({ lifeId: legacy.lifeId }) });
    expect(legacyResponse.status).toBe(200);
    const legacyChronicle = (await legacyResponse.json()) as Chronicle;
    expect(legacyChronicle.lifeId).toBe(legacy.lifeId);
    expect(legacyChronicle.branches).toEqual([{ branchId: legacy.branchId, label: "Original life", parentBranchId: null, forkYear: null }]);
    expect(legacyChronicle.entries.length).toBeGreaterThan(0);
    // The legacy branch returns the unmodified builder's own data, unreshaped by the dispatch.
    expect(legacyChronicle).toEqual((await buildLifeChronicle(legacy.lifeId)).data);
  }, 120_000);

  it("honors the stored branch, and answers an unknown branch or unknown life with the legacy not-found", async () => {
    const explicit = await getLife(lifeRequest(FIRST.lifeId, FIRST.branchId), { params: Promise.resolve({ lifeId: FIRST.lifeId }) });
    expect(explicit.status).toBe(200);
    expect((await explicit.json()) as Chronicle).toEqual(first.chronicle);

    const wrongBranch = await getLife(lifeRequest(FIRST.lifeId, "branch-of-another-life"), { params: Promise.resolve({ lifeId: FIRST.lifeId }) });
    expect(wrongBranch.status).toBe(404);
    await expect(wrongBranch.json()).resolves.toEqual({ error: "Life not found." });

    const unknown = await getLife(lifeRequest("life-that-was-never-saved"), { params: Promise.resolve({ lifeId: "life-that-was-never-saved" }) });
    expect(unknown.status).toBe(404);
    await expect(unknown.json()).resolves.toEqual({ error: "Life not found." });
  }, 120_000);
});

describe("GET /api/lives/:lifeId/people/:personId — sheet activation (RI1d)", () => {
  it("serves a lifecycle person and the honest not-found, and keeps serving the legacy sheet", async () => {
    const response = await getPerson(personRequest(FIRST.lifeId, "protagonist"), { params: Promise.resolve({ lifeId: FIRST.lifeId, personId: "protagonist" }) });
    expect(response.status).toBe(200);
    const sheet = (await response.json()) as PersonSheet;
    expect(sheet.personId).toBe("protagonist");
    expect(sheet.name).toBe(FIRST.name);
    expect(sheet.relation).toBe("self");

    const unknown = await getPerson(personRequest(FIRST.lifeId, "nobody-in-this-life"), { params: Promise.resolve({ lifeId: FIRST.lifeId, personId: "nobody-in-this-life" }) });
    expect(unknown.status).toBe(404);
    await expect(unknown.json()).resolves.toEqual({ error: "Person not found." });

    const legacySheet = await getPerson(personRequest(legacy.lifeId, "protagonist"), { params: Promise.resolve({ lifeId: legacy.lifeId, personId: "protagonist" }) });
    expect(legacySheet.status).toBe(200);
    const legacySheetBody = (await legacySheet.json()) as PersonSheet;
    expect(legacySheetBody.personId).toBe("protagonist");
    expect(legacySheetBody).toEqual((await buildPersonSheet(legacy.lifeId, "protagonist")).data);
  }, 120_000);
});

describe("GET /api/lives/:lifeId — refused capsule (RI1d)", () => {
  it("serves the index for a tampered capsule and refuses it once the index is gone", async () => {
    const db = getDb();
    const digest = (await new LifecycleRepository(db).load(FIRST.lifeId, FIRST.branchId))!.capsule.digest;
    const key = Buffer.from(digest, "utf16le");
    const stored = db.prepare("SELECT wire FROM main.lifecycle_capsules_v1 WHERE key = ?").get(key) as { wire: Uint8Array };
    const envelope = JSON.parse(Buffer.from(stored.wire).toString("utf16le")) as { digest: string };
    envelope.digest = "0".repeat(64);
    db.prepare("UPDATE main.lifecycle_capsules_v1 SET wire = ? WHERE key = ?").run(Buffer.from(JSON.stringify(envelope), "utf16le"), key);
    try {
      // P3's deliberate cost: the index answers by capsule digest without re-proving regeneration.
      const indexed = await getLife(lifeRequest(FIRST.lifeId), { params: Promise.resolve({ lifeId: FIRST.lifeId }) });
      expect(indexed.status).toBe(200);
      expect((await indexed.json()) as Chronicle).toEqual(first.chronicle);
      // Without the index, the replay path refuses the same bytes instead of repairing them.
      db.prepare("DELETE FROM main.lifecycle_projections_v1").run();
      const response = await getLife(lifeRequest(FIRST.lifeId), { params: Promise.resolve({ lifeId: FIRST.lifeId }) });
      expect(response.status).toBe(500);
      const body = (await response.json()) as { error?: string; data?: unknown };
      expect(body.error).toMatch(/digest disagreement/i);
      expect(body).toEqual({ error: body.error });
    } finally {
      db.prepare("UPDATE main.lifecycle_capsules_v1 SET wire = ? WHERE key = ?").run(stored.wire, key);
    }
    // Restored: the same request is the same life again, and the miss re-indexes it.
    const restored = await getLife(lifeRequest(FIRST.lifeId), { params: Promise.resolve({ lifeId: FIRST.lifeId }) });
    expect(restored.status).toBe(200);
    expect((await restored.json()) as Chronicle).toEqual(first.chronicle);
  }, 120_000);
});
