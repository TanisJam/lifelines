/**
 * RI1b (spec S8): the read-side projection derives the app's existing view model from a trusted,
 * fully regenerated lifecycle capsule. Every expectation below is computed from the trusted
 * `genesis`/`output` pair itself — the projection gets no other source it could legitimately use.
 */
const initialization = {
  seed: "ri1b-projection-1", startYear: 1327, endYear: 1327, founderCount: 4,
  protagonist: { name: "Alice", sex: "random" },
};
const identity = { lifeId: "life-ri1b", branchId: "branch-ri1b" } as const;

let source: LifecycleProjectionSource;
let chronicle: Awaited<ReturnType<typeof projectLifecycleChronicle>>;
let timeline: Awaited<ReturnType<typeof narratePersonTimeline>>;
let times: Map<string, number>;
let protagonistId: string;
let deathEventId: string;
let deathAt: number;
let PEOPLE: Readonly<Record<string, Person>>;
let EVENTS: readonly Event[];

/** One complete life, regenerated by the runtime itself: nothing here is hand-built evidence. */
async function completedLife(): Promise<LifecycleProjectionSource> {
  const { world } = initializeWorld(initialization);
  const genesis = createLifecycleGenesis({
    initialization, protagonistId: "protagonist",
    resources: Object.fromEntries(Object.keys(world.people).map((id) => [id, { grain: 2, effort: 3, need: 1 }])),
  });
  const runtime = createLifecycleRuntime(genesis);
  let output = runtime.snapshot();
  for (let steps = 0; output.status !== "complete" && steps < 128; steps++) output = await runtime.advance(output.frontier + 1);
  expect(output.status).toBe("complete");
  return { genesis, output };
}

/**
 * The regenerated output's own people and events, read as the domain's shapes. The runtime deep-
 * freezes its publication, which only removes mutability (`readonly` arrays where the domain types
 * are mutable); the shape is the same generated `Person`/`Event`, and neither the projection nor
 * narration ever writes to what it is given — the determinism test below pins that.
 */
function peopleOf(pair: LifecycleProjectionSource): Readonly<Record<string, Person>> {
  return pair.output.owned.people as unknown as Readonly<Record<string, Person>>;
}
function eventsOf(pair: LifecycleProjectionSource): readonly Event[] {
  return pair.output.owned.events as unknown as readonly Event[];
}
function decisionsOf(pair: LifecycleProjectionSource): readonly DecisionRecord[] {
  return pair.output.owned.decisions as unknown as readonly DecisionRecord[];
}

/** `readonly` removed at one level: a frozen source cannot be forged in place. */
type Mutable<T> = { -readonly [K in keyof T]: T[K] };

/** A mutable clone of the trusted pair, so a test can forge exactly one field of it. */
function forgeable(pair: LifecycleProjectionSource): {
  genesis: Mutable<LifecycleProjectionSource["genesis"]>;
  output: Mutable<LifecycleProjectionSource["output"]>;
} {
  return structuredClone(pair) as unknown as {
    genesis: Mutable<LifecycleProjectionSource["genesis"]>;
    output: Mutable<LifecycleProjectionSource["output"]>;
  };
}

/** The same end-of-year state a legacy branch stores as its `snapshots` entry. */
function endOfYear(year: number, owned: unknown): YearSnapshot {
  const state = owned as { people: Readonly<Record<string, Person>>; events: readonly Event[]; decisions: readonly DecisionRecord[] };
  return { year, people: state.people, events: state.events, decisions: state.decisions };
}

beforeAll(async () => {
  source = await completedLife();
  protagonistId = source.output.protagonistId;
  PEOPLE = peopleOf(source);
  EVENTS = eventsOf(source);
  const config = source.genesis.initial.config;
  chronicle = await projectLifecycleChronicle({ source, identity, locale: "en" });
  timeline = await narratePersonTimeline(protagonistId, EVENTS, PEOPLE, undefined, 8, config.seed, config.town.name, "en");
  times = eventTimes(config.seed, EVENTS, protagonistId);
  deathEventId = EVENTS.find((event) => event.kind === "death" && event.actors[0] === protagonistId)!.id;
  deathAt = times.get(deathEventId)!;
}, 240_000);

describe("lifecycle view projection (RI1b)", () => {
  it("projects every chronicle field the trusted output carries", () => {
    const config = source.genesis.initial.config;
    const protagonist = PEOPLE[protagonistId]!;
    const deathEvent = EVENTS.find((event) => event.kind === "death" && event.actors[0] === protagonistId)!;
    const { view } = chronicle;

    expect(view.lifeId).toBe(identity.lifeId);
    expect(view.branchId).toBe(identity.branchId);
    expect(view.villageName).toBe(config.town.name);
    expect(view.protagonist).toEqual({
      name: protagonist.name,
      sex: protagonist.sex,
      birthYear: protagonist.birthYear,
      deathYear: protagonist.deathYear,
      ageAtDeath: protagonist.deathYear! - protagonist.birthYear,
      causeOfDeath: view.protagonist.causeOfDeath,
    });
    // A recorded, recognized cause is rendered by the same domain display the legacy path uses.
    const causeCode = deathEvent.payload.cause as DeathCause;
    expect(view.protagonist.causeOfDeath).toBe(
      typeof causeCode === "string" && causeCode in DEATH_CAUSE_PHRASE ? deathCauseDisplay("en", causeCode) : "misfortune",
    );

    expect(view.summary.length).toBeGreaterThan(0);
    expect(view.summaryLinks.every((link) => view.summary.includes(`{{${link.personId}}}`))).toBe(true);
    expect(view.summaryLinks.every((link) => PEOPLE[link.personId]?.name === link.name)).toBe(true);
    expect(view.epilogue).toEqual(buildEpilogue(protagonist, PEOPLE, config.town.name, "en"));

    const { view: protagonistOnly } = projectLifecycleProtagonist({ source, locale: "en" });
    expect(protagonistOnly).toEqual(view.protagonist);
    expect(chronicle.gaps.map((gap) => gap.field)).not.toContain("chronicle.protagonist");
  }, 240_000);

  it("projects exactly the protagonist's narrated events with their trusted leaves", () => {
    const people = PEOPLE;
    const events = EVENTS;
    const byId = new Map(events.map((event) => [event.id, event]));
    const decisionByEventId = new Map<string, DecisionRecord>();
    for (const decision of decisionsOf(source)) for (const eventId of decision.resultingEventIds) decisionByEventId.set(eventId, decision);
    const sceneIds = new Set(chronicle.view.scene.people.map((person) => person.id));
    const byEntryId = new Map(chronicle.view.entries.map((entry) => [entry.id, entry]));
    const narratedById = new Map(timeline.map((narrated) => [narrated.event.id, narrated]));

    expect(chronicle.view.entries.length).toBeGreaterThan(0);
    for (const entry of chronicle.view.entries) {
      const event = byId.get(entry.id);
      expect(event).toBeDefined();
      expect(entry.year).toBe(event!.year);
      expect(entry.kind).toBe(event!.kind);
      expect(entry.who).toEqual(event!.actors.filter((id) => sceneIds.has(id)));
      expect(entry.at).toBe(times.get(entry.id));
      expect([1, 2, 3]).toContain(entry.level);
      expect(entry.title.length).toBeGreaterThan(0);
      expect(entry.prose.length).toBeGreaterThan(0);
      // Prose is the same narration the whole-life legacy path produces from the same inputs, with
      // exactly the `{{personId}}` markers the link-marking step adds.
      const narrated = narratedById.get(entry.id)!;
      expect(entry.title).toBe(narrated.title);
      expect(entry.prose).toBe(
        entry.links.reduce((text, link) => text.split(link.name).join(`{{${link.personId}}}`), narrated.prose),
      );
      expect(entry.links.every((link) => entry.prose.includes(`{{${link.personId}}}`))).toBe(true);
      // Markers only ever name people this event involves, and never the protagonist themselves.
      expect(entry.links.every((link) => event!.actors.includes(link.personId) && link.personId !== protagonistId)).toBe(true);

      const decision = decisionByEventId.get(entry.id);
      const isProtagonistDeath = event!.kind === "death" && event!.actors[0] === protagonistId;
      const isTurn = decision !== undefined && (isProtagonistDeath || isRealTurn(decision));
      if (isTurn) {
        expect(entry.level).toBe(3);
        expect(entry.turn).toBeDefined();
        expect(entry.turn!.decisionId).toBe(decision!.id);
        expect(entry.turn!.chosen.optionId).toBe(decision!.chosen);
        expect(entry.turn!.probabilities).toEqual(decision!.final);
        expect(entry.turn!.alternatives.map((option) => option.optionId)).not.toContain(decision!.chosen);
        expect(entry.turn!.occurrenceProbability).toBe(decision!.occurrenceProbability);
      } else if (!isProtagonistDeath) {
        expect(entry.turn).toBeUndefined();
      }
      // Kind-driven levels are rule-based in `life-chronicle`, and apply only when no real turn has
      // already raised the entry — a `vignette` that passed `isRealTurn` is a turn, not level 1.
      if (!isTurn && !isProtagonistDeath) {
        if (event!.kind === "vignette") expect(entry.level).toBe(1);
        if (event!.kind === "marriage") expect(entry.level).toBe(2);
      }

      const causeEvent = event!.causes.map((id) => byId.get(id)).find((candidate) => candidate !== undefined && candidate.year < event!.year);
      if (causeEvent) {
        const phrase = causeNounPhrase(causeEvent, protagonistId, people);
        if (phrase === null) expect(entry.cause).toBeUndefined();
        else {
          expect(entry.cause?.phrase).toBe(phrase);
          expect(entry.cause?.year).toBe(causeEvent.year);
          // The link is the cause's own entry id whenever that entry is part of this chronicle.
          expect(entry.cause?.entryId).toBe(byEntryId.has(causeEvent.id) ? causeEvent.id : undefined);
        }
      }
    }
  }, 240_000);

  it("orders entries by the trusted moment and keeps the trusted log order for ties", () => {
    // Expected order: the trusted narrated-log order, stable-sorted by the moment derived from
    // (seed, events) — never by an invented key — and cut at the protagonist's own death.
    const expected = timeline
      .map((narrated, index) => ({ id: narrated.event.id, index, at: times.get(narrated.event.id)! }))
      .filter((item) => item.at <= deathAt)
      .sort((left, right) => left.at - right.at || left.index - right.index)
      .map((item) => item.id);
    expect(chronicle.view.entries.map((entry) => entry.id)).toEqual(expected);

    const projected = chronicle.view.entries.map((entry) => entry.at);
    expect(projected).toEqual([...projected].sort((left, right) => left - right));
  }, 240_000);

  it("tells nothing after the protagonist's own death", () => {
    const entries = chronicle.view.entries;
    expect(entries.at(-1)!.id).toBe(deathEventId);
    expect(entries.at(-1)!.level).toBe(3);
    for (const entry of entries) expect(entry.at).toBeLessThanOrEqual(deathAt);
  }, 60_000);

  it("derives the scene from the trusted journal in its own traversal order", () => {
    const config = source.genesis.initial.config;
    const tracker = createSceneTracker({ seed: config.seed, protagonistId });
    for (const year of source.output.journal) {
      tracker.observe(endOfYear(year.year, year.final.owned));
    }
    const expected = tracker.scene({ people: PEOPLE, events: EVENTS });
    expect(chronicle.view.scene).toEqual(expected);

    const sceneIds = new Set(chronicle.view.scene.people.map((person) => person.id));
    expect(chronicle.view.scene.people.filter((person) => person.relCode === "self").map((person) => person.id)).toEqual([protagonistId]);
    expect(chronicle.view.scene.span.end).toBe(deathAt);
    expect(chronicle.view.scene.span.start).toBeLessThanOrEqual(deathAt);
    expect(chronicle.view.scene.village.every((soul) => !sceneIds.has(soul.k))).toBe(true);
    expect(chronicle.view.scene.people.every((person) => PEOPLE[person.id] !== undefined)).toBe(true);
  }, 240_000);

  it("projects one tick from the same trusted source", async () => {
    const lastYear = source.output.journal.at(-1)!.year;
    const tick = await projectLifecycleTick({ source, year: lastYear, locale: "en" });
    expect(tick.view.year).toBe(lastYear);
    expect(tick.view.scene).toEqual(chronicle.view.scene);
    // A tick is that year exactly as the legacy live tick reports it: every entry narrated for the
    // year in trusted log order, with no death cut. The chronicle is the cut view, so its entries
    // for the same year are the tick's minus everything dated at or after the protagonist's death.
    const yearIds = timeline.filter((narrated) => narrated.event.year === lastYear).map((narrated) => narrated.event.id);
    expect(tick.view.entries.map((entry) => entry.id)).toEqual(yearIds);
    expect(chronicle.view.entries.filter((entry) => entry.year === lastYear).map((entry) => entry.id)).toEqual(
      yearIds.filter((id) => times.get(id)! <= deathAt),
    );
    expect(tick.gaps.map((gap) => gap.field)).toEqual(["tick.entries[].level"]);

    const firstYear = source.output.journal[0]!.year;
    const firstTick = await projectLifecycleTick({ source, year: firstYear, locale: "en" });
    expect(firstTick.view.scene.span.end).toBeNull();
    // As of that year the sky cannot know a death that has not happened yet.
    expect(firstTick.view.scene.people.find((person) => person.id === protagonistId)?.diedAt).toBeUndefined();
    expect(firstTick.view.scene.people.every((person) => chronicle.view.scene.people.some((final) => final.id === person.id))).toBe(true);

    await expect(projectLifecycleTick({ source, year: lastYear + 500 })).rejects.toThrow(/Lifecycle projection/);
  }, 240_000);

  it("reports every field it cannot fill instead of inventing one", () => {
    expect(chronicle.gaps.map((gap) => gap.field)).toEqual([
      "chronicle.lifeId",
      "chronicle.branchId",
      "chronicle.branches",
      "chronicle.entries[].level",
    ]);
    for (const gap of chronicle.gaps) {
      expect(gap.reason.length).toBeGreaterThan(0);
      expect(gap.representation.length).toBeGreaterThan(0);
    }
    // The representation each gap declares is what the view actually shows.
    expect(chronicle.view.branches).toEqual([]);
    expect(chronicle.view.entries.every((entry) => Number.isInteger(entry.level))).toBe(true);
    expect(chronicle.view.entries.every((entry) => entry.proseTokens === undefined)).toBe(true);
  }, 60_000);

  it("is deterministic and never mutates or freezes its input", async () => {
    const mutable: LifecycleProjectionSource = structuredClone({ genesis: source.genesis, output: source.output });
    const before = structuredClone(mutable);
    const first = await projectLifecycleChronicle({ source: mutable, identity, locale: "en" });
    const second = await projectLifecycleChronicle({ source: mutable, identity, locale: "en" });
    expect(second.view).toEqual(first.view);
    expect(second.gaps).toEqual(first.gaps);
    expect(structuredClone(mutable)).toEqual(before);
    expect(Object.isFrozen(mutable)).toBe(false);
    expect(Object.isFrozen(mutable.genesis)).toBe(false);
    expect(Object.isFrozen(mutable.output)).toBe(false);
    expect(Object.isFrozen(mutable.output.owned.people[protagonistId])).toBe(false);
    // The production source is deeply frozen by regeneration and stays that way.
    expect(Object.isFrozen(source.output)).toBe(true);
    expect(Object.isFrozen(source.output.owned.people[protagonistId])).toBe(true);
  }, 240_000);

  it("refuses a foreign or malformed source with a clear error", async () => {
    const incomplete = (() => {
      const { world } = initializeWorld(initialization);
      const genesis = createLifecycleGenesis({
        initialization, protagonistId: "protagonist",
        resources: Object.fromEntries(Object.keys(world.people).map((id) => [id, { grain: 2, effort: 3, need: 1 }])),
      });
      return { genesis, runtime: createLifecycleRuntime(genesis) };
    })();
    await incomplete.runtime.advance(source.genesis.initial.config.startYear);
    const unfinished: LifecycleProjectionSource = { genesis: incomplete.genesis, output: incomplete.runtime.snapshot() };
    const forgedVersion = forgeable(source);
    (forgedVersion.output as { versions: Record<string, unknown> }).versions = {
      ...forgedVersion.output.versions, schema: "annual-capsule-rb1-1",
    };
    const disagreed = forgeable(source);
    disagreed.genesis.protagonistId = "someone-else";

    const refusals: unknown[] = [
      undefined,
      {},
      { genesis: source.genesis },
      { config: {}, people: {}, events: [], decisions: [] },
      { genesis: source.genesis, output: { ...structuredClone(source.output), status: "finished" } },
      forgedVersion,
      disagreed,
    ];
    for (const refusal of refusals) {
      await expect(projectLifecycleChronicle(refusal as never)).rejects.toThrow(/Lifecycle projection/);
    }
    await expect(projectLifecycleChronicle({ source: unfinished, identity })).rejects.toThrow(/Lifecycle projection/);
    await expect(projectLifecycleChronicle({ source, identity: { lifeId: "", branchId: "branch" } })).rejects.toThrow(/Lifecycle projection/);
    await expect(projectLifecycleTick({ source, year: 1.5 })).rejects.toThrow(/Lifecycle projection/);
  }, 240_000);

  it("is never authority: it does not admit, replay or verify what it projects", async () => {
    // A forged source: one person's name no longer matches what regeneration produces. The forgery
    // sits only in the final output — a journal year's own record is a separate clone — so the
    // rejection below is reached only after EVERY regenerated journal year agreed, which is the
    // pristine control and the forgery in one observation.
    const forged = forgeable(source);
    (forged.output.owned.people[protagonistId] as { name: string }).name = "Forged Name";
    await expect(replayLifecycleRuntime({ genesis: forged.genesis, output: forged.output }))
      .rejects.toThrow(/Lifecycle final output disagreement/);

    // The projection maps whatever pair it is handed: it holds no authority to verify — it reads no
    // digest and replays no year — so a view built from a source regeneration refuses is exactly as
    // trustworthy as its caller made it, and never a certificate that the life happened this way.
    const projected = await projectLifecycleChronicle({ source: forged, identity, locale: "en" });
    expect(projected.view.protagonist.name).toBe("Forged Name");
  }, 240_000);

  it("imports no persistence, clock, randomness or authority recomputation", () => {
    const sourceText = readFileSync(new URL("./lifecycle-projection.ts", import.meta.url), "utf8");
    const runtimeImports = sourceText.split("\n").filter((line) => line.startsWith("import ") && !line.startsWith("import type "));
    for (const line of runtimeImports) {
      expect(line).not.toMatch(/["'](?:node:)?(?:fs|sqlite|crypto|path)["']/);
      expect(line).not.toMatch(/["'][^"']*(?:\/db|life-store|lifecycle-repository|e-branch-repository|decision-engine|e-lifecycle-replay|e-lifecycle-capsule)["']/);
    }
    expect(sourceText).not.toMatch(/Math\.random|Date\.now|new Date|performance\.now|createHash/);
  });

  it("projects a person sheet from the same trusted output", async () => {
    const people = PEOPLE;
    const protagonist = people[protagonistId]!;
    const sheet = await projectLifecyclePersonSheet({ source, personId: protagonistId, locale: "en" });
    expect(sheet.view).toEqual({
      personId: protagonistId,
      name: protagonist.name,
      relation: "self",
      birthYear: protagonist.birthYear,
      deathYear: protagonist.deathYear ?? null,
      job: protagonist.job === "none" ? null : protagonist.job,
      blurb: renderPortrait(protagonist.name, protagonist.mind, (id) => people[id]?.name ?? id),
      moments: sheet.view.moments,
    });
    expect(sheet.view.moments.length).toBeLessThanOrEqual(5);
    expect(sheet.view.moments.map((moment) => moment.year)).toEqual(
      [...sheet.view.moments.map((moment) => moment.year)].sort((left, right) => left - right),
    );
    expect(sheet.gaps.map((gap) => gap.field)).toEqual(["personSheet.moments"]);

    const other = chronicle.view.scene.people.find((person) => person.relCode !== "self")!;
    const otherSheet = await projectLifecyclePersonSheet({ source, personId: other.id, locale: "en" });
    const expectedRelation = familyRelation(protagonist, people[other.id]!)
      ?? protagonist.mind.relationships.find((relationship) => relationship.personId === other.id)?.bond
      ?? "acquaintance";
    expect(otherSheet.view.relation).toBe(expectedRelation);
    expect(otherSheet.view.blurb).toBe(renderPortrait(people[other.id]!.name, people[other.id]!.mind, (id) => people[id]?.name ?? id));

    await expect(projectLifecyclePersonSheet({ source, personId: "not-a-person" })).rejects.toThrow(/Lifecycle projection/);
  }, 240_000);
});
