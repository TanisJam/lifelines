import { createHash } from "node:crypto";
import { admitLifecycleGenesis, canonicalLifecycleData, LIFECYCLE_GENESIS_VERSIONS,
  type LifecycleGenesis } from "./e-lifecycle-genesis";
import { deserializeCompactLifecycleDag, serializeCompactLifecycleDag } from "./e-lifecycle-dag";
import { replayLifecycleRuntime } from "./e-lifecycle-replay";
import { requireFavorData } from "./effects";
import { requireFields } from "./obligations";

/** Separate from the frozen E1/C2/E3 codecs; no implicit migration. */
export const LIFECYCLE_CAPSULE_MANIFEST = Object.freeze({
  capsuleSchema: "lifecycle-capsule-lr2b-1",
  codec: "sorted-own-data-tuples-lr2b-1",
  ...LIFECYCLE_GENESIS_VERSIONS,
});
export type LifecycleCapsuleManifest = typeof LIFECYCLE_CAPSULE_MANIFEST;
export interface LifecycleCapsule {
  readonly manifest: LifecycleCapsuleManifest;
  readonly digest: string;
  readonly genesis: LifecycleGenesis;
  readonly output: Awaited<ReturnType<typeof replayLifecycleRuntime>>;
}

function record(value: unknown): asserts value is Record<string, unknown> {
  if (value === null || typeof value !== "object" || Array.isArray(value)) throw new Error("Expected lifecycle capsule record");
}
function freeze<T>(value: T): T {
  if (value !== null && typeof value === "object") {
    for (const entry of Object.values(value)) freeze(entry);
    Object.freeze(value);
  }
  return value;
}
/**
 * Identity memo for capsules THIS process regenerated and froze.
 *
 * Re-admitting such a capsule cannot discover anything: its manifest, digest and
 * full replay were just verified here, and the graph is deeply frozen. The create
 * path admits the same capsule three times (`createLifecycleCompactCapsule`,
 * `publish`, `serializeLifecycleCompactCapsule`), and each admission re-runs the
 * complete replay - four executions of the same deterministic run for one life.
 *
 * This is NOT a trust path. Caller-supplied data is never in this set, so an
 * external capsule is still fully regenerated. Removing a recomputation of our
 * own frozen output does not weaken any admission boundary.
 */
const certifiedLexicon = {
  legacy: new WeakSet<object>(),
  compact: new WeakSet<object>(),
} as const;
function isCertified<T extends object>(format: keyof typeof certifiedLexicon, value: unknown): value is T {
  return typeof value === "object" && value !== null && certifiedLexicon[format].has(value);
}
/**
 * Outputs this process already regenerated by a full replay. A compact encode of an
 * already-replayed output needs no second replay, but ONLY when the output is bound to
 * the exact genesis being admitted (`output.genesisDigest`), so a mismatched pair is
 * still fully replayed instead of certified.
 */
const certifiedOutputs = new WeakSet<object>();
function replayOrReuse(genesis: LifecycleGenesis, output: unknown) {
  if (typeof output === "object" && output !== null && certifiedOutputs.has(output)
    && (output as { genesisDigest?: unknown }).genesisDigest === genesis.digest) {
    return output as Awaited<ReturnType<typeof replayLifecycleRuntime>>;
  }
  return replayLifecycleRuntime({ genesis, output });
}
function checkedRecord(input: unknown, fields: string[]): Record<string, unknown> {
  // WHOLE borrowed graph before any field read, hashing, cloning or await.
  requireFavorData(input, true);
  record(input);
  requireFields(input, fields);
  // Borrow only within this synchronous scope; regenerate immediately captures
  // ownership through genesis admission and replay before either can suspend.
  return input;
}
function requireManifest(value: unknown): void {
  if (canonicalLifecycleData(value) !== canonicalLifecycleData(LIFECYCLE_CAPSULE_MANIFEST)) {
    throw new Error("Unsupported lifecycle capsule manifest");
  }
}
function payload(genesis: unknown, output: unknown): string {
  // The sole encoder is the unchanged genesis grammar, not a parallel wire codec.
  return canonicalLifecycleData({ genesis, output });
}
function hashEscaped(hash: ReturnType<typeof createHash>, encoded: string): void {
  for (let start = 0; start < encoded.length;) {
    let end = Math.min(start + 32768, encoded.length);
    // Native JSON escaping must see paired UTF-16 units together. Lone
    // surrogates still receive JSON.stringify's original well-formed escaping.
    if (end < encoded.length) {
      const high = encoded.charCodeAt(end - 1);
      const low = encoded.charCodeAt(end);
      if (high >= 0xd800 && high <= 0xdbff && low >= 0xdc00 && low <= 0xdfff) end--;
    }
    hash.update(JSON.stringify(encoded.slice(start, end)).slice(1, -1), "utf8");
    start = end;
  }
}
function digest(manifest: unknown, encoded: string): string {
  // A JSON tuple frames two strings unambiguously. Both complete manifest and
  // complete tagged genesis/output participate; digest itself never does.
  const hash = createHash("sha256");
  hash.update(`[${JSON.stringify(canonicalLifecycleData(manifest))},"`, "utf8");
  hashEscaped(hash, encoded);
  hash.update('\"]', "utf8");
  return hash.digest("hex");
}
function requireDigest(value: unknown, manifest: unknown, encoded: string): asserts value is string {
  if (typeof value !== "string" || !/^[a-f0-9]{64}$/.test(value) || value !== digest(manifest, encoded)) {
    throw new Error("Lifecycle capsule digest disagreement");
  }
}
async function regenerate(candidate: Record<string, unknown>): Promise<LifecycleCapsule> {
  // Digest is integrity, NEVER execution authority. LR1a regenerates genesis;
  // LR2a independently regenerates every native/economic year and all evidence.
  // Genesis admission detaches synchronously. Replay guards/clones its whole
  // envelope before its first await; after this await never read candidate again.
  const genesis = admitLifecycleGenesis(candidate.genesis);
  const output = await replayOrReuse(genesis, candidate.output);
  certifiedOutputs.add(output);
  const manifest = freeze(structuredClone(LIFECYCLE_CAPSULE_MANIFEST));
  const capsule = Object.freeze({ manifest, digest: digest(manifest, payload(genesis, output)), genesis, output });
  certifiedLexicon.legacy.add(capsule);
  return capsule;
}

/** Required closed input { genesis, output }, including zero-year/alive/death output. */
export async function createLifecycleCapsule(input: unknown): Promise<LifecycleCapsule> {
  return regenerate(checkedRecord(input, ["genesis", "output"]));
}
/** Cold admission always performs full trusted replay, including rehashed candidates. */
export async function admitLifecycleCapsule(input: unknown): Promise<LifecycleCapsule> {
  if (isCertified<LifecycleCapsule>("legacy", input)) return input;
  const candidate = checkedRecord(input, ["manifest", "digest", "genesis", "output"]);
  requireManifest(candidate.manifest);
  requireDigest(candidate.digest, candidate.manifest, payload(candidate.genesis, candidate.output));
  return regenerate(candidate);
}
function wire(capsule: LifecycleCapsule): string {
  // Manifest declaration order and envelope order are fixed; payload sorts records.
  return JSON.stringify({ manifest: capsule.manifest, payload: payload(capsule.genesis, capsule.output), digest: capsule.digest });
}
export async function serializeLifecycleCapsule(input: unknown): Promise<string> {
  return wire(await admitLifecycleCapsule(input));
}

/** Strict inverse ONLY of canonicalLifecycleData's tagged grammar. No executable
 * coercion, prototype assignment, undefined pruning or alternate number grammar. */
function decode(value: unknown): unknown {
  if (!Array.isArray(value) || typeof value[0] !== "string") throw new Error("Invalid lifecycle tuple");
  const [tag, item] = value;
  if (tag === "undefined" || tag === "null") {
    if (value.length !== 1) throw new Error("Invalid lifecycle leaf arity");
    return tag === "undefined" ? undefined : null;
  }
  if (value.length !== 2) throw new Error("Invalid lifecycle tuple arity");
  if (tag === "string" || tag === "boolean") {
    if (typeof item !== tag) throw new Error("Invalid lifecycle leaf");
    return item;
  }
  if (tag === "number") {
    if (typeof item !== "string") throw new Error("Invalid lifecycle number");
    const number = Number(item);
    if (!Number.isFinite(number) || (Object.is(number, -0) ? "-0" : String(number)) !== item) {
      throw new Error("Noncanonical lifecycle number");
    }
    return number;
  }
  if (!Array.isArray(item)) throw new Error("Invalid lifecycle container");
  if (tag === "array") return item.map(decode);
  if (tag !== "record") throw new Error("Unsupported lifecycle tag");
  const result = Object.create(null) as Record<string, unknown>;
  for (const pair of item) {
    if (!Array.isArray(pair) || pair.length !== 2 || typeof pair[0] !== "string" || Object.hasOwn(result, pair[0])) {
      throw new Error("Invalid or duplicate lifecycle record key");
    }
    Object.defineProperty(result, pair[0], { value: decode(pair[1]), enumerable: true, writable: true, configurable: true });
  }
  return result;
}
export async function deserializeLifecycleCapsule(input: unknown): Promise<LifecycleCapsule> {
  if (typeof input !== "string") throw new Error("Expected lifecycle capsule wire string");
  const envelope: unknown = JSON.parse(input);
  requireFavorData(envelope, true);
  record(envelope);
  requireFields(envelope, ["manifest", "payload", "digest"]);
  requireManifest(envelope.manifest);
  if (typeof envelope.payload !== "string") throw new Error("Expected lifecycle tagged payload string");
  const candidate = decode(JSON.parse(envelope.payload));
  if (canonicalLifecycleData(candidate) !== envelope.payload) throw new Error("Noncanonical lifecycle payload");
  requireDigest(envelope.digest, envelope.manifest, envelope.payload);
  // JSON.parse alone loses duplicates and syntax variants. Require exact bytes,
  // including manifest declaration order, escapes and outer envelope field order.
  const canonicalWire = JSON.stringify({ manifest: LIFECYCLE_CAPSULE_MANIFEST, payload: envelope.payload, digest: envelope.digest });
  if (canonicalWire !== input) throw new Error("Noncanonical lifecycle capsule wire");
  record(candidate);
  requireFields(candidate, ["genesis", "output"]);
  return regenerate(candidate);
}

/** Additive compact FORMAT. Recognized ONLY by its own manifest: it is not a
 * trust flag, not a migration path, and it never replaces the legacy wire. */
export const LIFECYCLE_COMPACT_CAPSULE_MANIFEST = Object.freeze({
  capsuleSchema: "lifecycle-capsule-compact-cb1-1",
  codec: "canonical-dag-dictionary-cb1-1",
  ...LIFECYCLE_GENESIS_VERSIONS,
});
export type LifecycleCompactCapsuleManifest = typeof LIFECYCLE_COMPACT_CAPSULE_MANIFEST;
export interface LifecycleCompactCapsule {
  readonly manifest: LifecycleCompactCapsuleManifest;
  readonly digest: string;
  readonly genesis: LifecycleGenesis;
  readonly output: LifecycleCapsule["output"];
}
const COMPACT_DOMAIN = "lifecycle-compact-capsule-cb1-1";
function requireCompactManifest(value: unknown): void {
  if (canonicalLifecycleData(value) !== canonicalLifecycleData(LIFECYCLE_COMPACT_CAPSULE_MANIFEST)) {
    throw new Error("Unsupported lifecycle compact capsule manifest");
  }
}
function compactPayload(genesis: unknown, output: unknown): string {
  // The canonical COMPACT dictionary wire, never the unfolded tagged grammar.
  return serializeCompactLifecycleDag({ genesis, output });
}
function compactDigest(manifest: unknown, table: string): string {
  // Domain-separated from the legacy frame: a different prefix and arity mean
  // no legacy bytes can be replayed as a compact capsule, or the reverse.
  const hash = createHash("sha256");
  hash.update(`["${COMPACT_DOMAIN}",${JSON.stringify(canonicalLifecycleData(manifest))},"`, "utf8");
  hashEscaped(hash, table);
  hash.update('\"]', "utf8");
  return hash.digest("hex");
}
function requireCompactDigest(value: unknown, manifest: unknown, table: string): asserts value is string {
  if (typeof value !== "string" || !/^[a-f0-9]{64}$/.test(value) || value !== compactDigest(manifest, table)) {
    throw new Error("Lifecycle compact capsule digest disagreement");
  }
}
async function regenerateCompact(candidate: Record<string, unknown>): Promise<LifecycleCompactCapsule> {
  // Same authority rule as the legacy format: digest is integrity only, genesis
  // is re-admitted and every native/economic year is fully replayed here.
  const genesis = admitLifecycleGenesis(candidate.genesis);
  const output = await replayOrReuse(genesis, candidate.output);
  certifiedOutputs.add(output);
  const manifest = freeze(structuredClone(LIFECYCLE_COMPACT_CAPSULE_MANIFEST));
  const table = compactPayload(genesis, output);
  const capsule = Object.freeze({ manifest, digest: compactDigest(manifest, table), genesis, output });
  certifiedLexicon.compact.add(capsule);
  return capsule;
}
/** Required closed input { genesis, output }, identical admission to the legacy format. */
export async function createLifecycleCompactCapsule(input: unknown): Promise<LifecycleCompactCapsule> {
  return regenerateCompact(checkedRecord(input, ["genesis", "output"]));
}
/** Cold admission re-derives the compact table from regenerated data, not from trust. */
export async function admitLifecycleCompactCapsule(input: unknown): Promise<LifecycleCompactCapsule> {
  if (isCertified<LifecycleCompactCapsule>("compact", input)) return input;
  const candidate = checkedRecord(input, ["manifest", "digest", "genesis", "output"]);
  requireCompactManifest(candidate.manifest);
  requireCompactDigest(candidate.digest, candidate.manifest, compactPayload(candidate.genesis, candidate.output));
  return regenerateCompact(candidate);
}
function compactWire(capsule: LifecycleCompactCapsule): string {
  return JSON.stringify({ manifest: capsule.manifest,
    table: compactPayload(capsule.genesis, capsule.output), digest: capsule.digest });
}
export async function serializeLifecycleCompactCapsule(input: unknown): Promise<string> {
  return compactWire(await admitLifecycleCompactCapsule(input));
}
export async function deserializeLifecycleCompactCapsule(input: unknown): Promise<LifecycleCompactCapsule> {
  if (typeof input !== "string") throw new Error("Expected lifecycle compact capsule wire string");
  const envelope: unknown = JSON.parse(input);
  requireFavorData(envelope, true);
  record(envelope);
  requireFields(envelope, ["manifest", "table", "digest"]);
  requireCompactManifest(envelope.manifest);
  if (typeof envelope.table !== "string") throw new Error("Expected lifecycle compact table string");
  requireCompactDigest(envelope.digest, envelope.manifest, envelope.table);
  // Complete closed dictionary decode BEFORE any current-authority replay: a
  // matching digest never buys materialization or an executable graph.
  const candidate = deserializeCompactLifecycleDag(envelope.table);
  record(candidate);
  requireFields(candidate, ["genesis", "output"]);
  // JSON.parse alone loses duplicates and syntax variants. Require exact bytes,
  // including manifest declaration order, escapes and outer envelope field order.
  const canonicalWire = JSON.stringify({ manifest: LIFECYCLE_COMPACT_CAPSULE_MANIFEST,
    table: envelope.table, digest: envelope.digest });
  if (canonicalWire !== input) throw new Error("Noncanonical lifecycle compact capsule wire");
  return regenerateCompact(candidate);
}
